"""RESOLVE and PLAN for the New state: compose layers, validate, render the plan in memory.

Nothing here touches the disk except read-only checks. The core contains no
technology names; everything specific lives in layers/ and templates/.
"""
import hashlib
import json
import re
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from . import gitops, pathsafe
from .render import fill
from .layers import (KIND_ORDER, ROLES, SUPPORTED_FORMAT, TEMPLATES_DIR, requirement_met)

TOOL_VERSION = "2.0"
SINGLE = ("category", "state", "distribution")
GITIGNORE_HEADER = "# Generated by the project scaffolder. Edit freely; this file is yours.\n"


class ResolveError(Exception):
    def __init__(self, problems):
        self.problems = list(problems)
        super().__init__("\n".join(self.problems))


@dataclass
class Choices:
    name: str
    folder: str
    picks: dict = field(default_factory=dict)      # kind -> [ids]
    versions: dict = field(default_factory=dict)   # 'kind:id' -> version text
    sources: dict = field(default_factory=dict)    # field -> user|default|inferred|detected
    git: bool = True
    git_workflow: str = "simple"
    first_commit: bool = False
    description: str = ""


@dataclass
class Resolved:
    choices: Choices
    layers: list
    implied: set
    cfg: dict
    root: Path
    files: dict          # path -> content (text)
    template_of: dict    # path -> template id or '(generated)'
    dirs: list           # explicit directories to create
    warnings: list
    descriptor: dict


def slugify(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s


def default_folder(name):
    return re.sub(r"\s+", "-", name.strip())


def git_workflows(templates_dir=TEMPLATES_DIR):
    """Workflow ids are data: one templates/v2/git-workflow-<id>.md per workflow."""
    return sorted(p.stem[len("git-workflow-"):] for p in (Path(templates_dir) / "v2").glob("git-workflow-*.md"))


def _ref(kind, ident):
    return f"{kind}:{ident}"


def expand(choices, catalog):
    """Ordered layer list; implied layers are inserted just before the layer that implies them."""
    problems, ordered, implied = [], [], set()
    seen = set()

    def add(ref, implier=None):
        if ref in seen:
            return
        layer = catalog.get(ref)
        if layer is None:
            kind = ref.split(":")[0]
            known = sorted(l.id for l in catalog.values() if l.kind == kind and not l.hidden)
            problems.append(f"Unknown {kind} '{ref.split(':', 1)[-1]}'. Available: {', '.join(known) or '(none)'}")
            return
        seen.add(ref)
        for dep in layer.data.get("implies", []):
            if dep not in seen:
                implied.add(dep)
                add(dep, ref)
        ordered.append(layer)

    add("base:base")
    for kind in KIND_ORDER[1:]:
        for ident in choices.picks.get(kind, []):
            add(_ref(kind, ident))
    return ordered, implied, problems


def validate_selection(layers, choices):
    problems = []
    refs = {l.ref for l in layers}
    for kind in SINGLE:
        n = sum(1 for l in layers if l.kind == kind)
        if n != 1:
            problems.append(f"Choose exactly one {kind} (got {n}).")
    if not any(l.kind == "platform" for l in layers):
        problems.append("Choose at least one platform.")
    for l in layers:
        for req in l.data.get("requires", []):
            if not requirement_met(req, refs):
                problems.append(f"'{l.label}' requires: {req.replace('|', ' or ')}.")
        for con in l.data.get("conflicts", []):
            for alt in con.split("|"):
                kind, _, ident = alt.partition(":")
                hit = any(r.startswith(kind + ":") for r in refs) if ident == "*" else alt in refs
                if hit:
                    problems.append(f"'{l.label}' cannot be combined with {alt.replace(':*', ' (any)')}.")
    return problems


def merge(layers, choices):
    cfg = {
        "roles": {r: None for r in ROLES}, "dirs": {}, "files": {}, "remove": [],
        "ignore": [], "qa": [], "questions": [], "commands": [], "conventions": [], "donts": [],
        "warnings": [], "recommendations": [], "must_fill": [], "protected_paths": [],
        "secret": [], "local_only": [], "generated": [], "watch": [], "large_file_warn_mb": 5,
        "toolchain": {}, "distribution": {"enabled": False}, "json_merge": {},
    }

    def union(key, items):
        for i in items:
            if i not in cfg[key]:
                cfg[key].append(i)

    for l in layers:
        d = l.data
        for role, spec in d.get("roles", {}).items():
            cfg["roles"][role] = None if spec is False else dict(spec)
        cfg["dirs"].update(d.get("dirs", {}))
        cfg["files"].update(d.get("files", {}))
        for path, value in d.get("json_merge", {}).items():
            cfg["json_merge"].setdefault(path, []).append((l.ref, value))
        for path in d.get("remove", []):
            cfg["dirs"].pop(path, None)
            cfg["files"].pop(path, None)
            cfg["json_merge"].pop(path, None)
        for key in ("ignore", "qa", "questions", "commands", "conventions", "donts", "warnings",
                    "recommendations", "must_fill", "protected_paths"):
            union(key, d.get(key, []))
        sec = d.get("security", {})
        for key in ("secret", "local_only", "generated", "watch"):
            union(key, sec.get(key, []))
        if "large_file_warn_mb" in sec:
            cfg["large_file_warn_mb"] = sec["large_file_warn_mb"]
        for k, v in d.get("toolchain", {}).items():
            if "{version}" in v:
                ver = choices.versions.get(l.ref, "").strip()
                if not ver:
                    continue
                v = v.replace("{version}", ver)
            cfg["toolchain"][k] = v
        if "distribution" in d:
            dist = dict(d["distribution"])
            prov = dist.pop("provenance", None)
            cfg["distribution"] = dist
            cfg["distribution"]["provenance"] = {"record": prov or []}
    local = cfg["roles"].get("local")
    cfg["local_paths"] = [local["path"]] if local else []
    return cfg


def _check_paths(cfg, templates_dir):
    problems = []
    role_paths = {}
    for role, spec in cfg["roles"].items():
        if not spec:
            continue
        problems += [f"role {role}: {m}" for m in pathsafe.check_rel_path(spec["path"])]
        role_paths.setdefault(spec["path"].casefold(), []).append(role)
    for path, roles in role_paths.items():
        if len(roles) > 1:
            problems.append(f"Roles {', '.join(roles)} are mapped to the same folder '{path}'.")
    for p in list(cfg["dirs"]) + list(cfg["files"]) + list(cfg["json_merge"]) + cfg["protected_paths"]:
        problems += [f"{m}" for m in pathsafe.check_rel_path(p)]
    for p in cfg["json_merge"]:
        if p in (".gitignore", ".project.json") or p in cfg["dirs"]:
            problems.append(f"'{p}' is a folder or a reserved name; cannot merge JSON.")
    for tpl in cfg["files"].values():
        if not (Path(templates_dir) / tpl).is_file():
            problems.append(f"Missing template: {tpl}")
    return problems


def _merge_json(contents, template_of, contributions, tokens):
    """Combine object fields; reject conflicting values rather than selecting a winner."""
    def combine(target, incoming, path, source, owners, location=()):
        for key, value in incoming.items():
            field = location + (key,)
            if key not in target:
                target[key] = {} if isinstance(value, dict) else value
                owners[field] = source
                if isinstance(value, dict):
                    combine(target[key], value, path, source, owners, field)
            elif isinstance(target[key], dict) and isinstance(value, dict):
                combine(target[key], value, path, source, owners, field)
            elif (type(target[key]) is not type(value)
                  or json.dumps(target[key], sort_keys=True) != json.dumps(value, sort_keys=True)):
                previous = next((owners[field[:i]] for i in range(len(field), -1, -1)
                                 if field[:i] in owners), "template")
                raise ResolveError([f"{path}: conflicting JSON field {'.'.join(field)} "
                                    f"between {previous} and {source}."])

    def substitute(value):
        if isinstance(value, str):
            return fill(value, tokens)
        if isinstance(value, dict):
            return {key: substitute(item) for key, item in value.items()}
        if isinstance(value, list):
            return [substitute(item) for item in value]
        return value

    for path, parts in contributions.items():
        try:
            value = json.loads(contents[path]) if path in contents else {}
            if not isinstance(value, dict):
                raise ValueError("base JSON must be an object")
            owners = {(): f"template {template_of.get(path, '(generated)')}"}
            for source, part in parts:
                incoming = substitute(part)
                # Reject TOML-only values (for example dates) and non-finite numbers.
                json.dumps(incoming, allow_nan=False)
                combine(value, incoming, path, source, owners)
            contents[path] = json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
            template_of[path] = template_of.get(path, "(generated)") + " + json_merge"
        except (ValueError, TypeError) as exc:
            raise ResolveError([f"{path}: cannot merge JSON ({exc})."]) from exc


def _gitignore(cfg):
    out = [GITIGNORE_HEADER.rstrip("\n"), "", "# Secrets (never commit)"] + cfg["secret"]
    local = []
    for p in cfg["local_paths"]:
        local += [f"/{p.rstrip('/')}/*", f"!/{p.rstrip('/')}/README.md"]
    local += cfg["local_only"]
    if local:
        out += ["", "# Local-only material (never committed)"] + local
    tool = [f"/{s['path'].rstrip('/')}/" for s in cfg["roles"].values() if s and s["origin"] == "tool_created"]
    gen = []
    for x in tool + cfg["generated"] + cfg["ignore"]:
        if x not in gen:
            gen.append(x)
    out += ["", "# Generated / tool-created"] + gen
    return "\n".join(out) + "\n"


def _tokens(choices, layers, cfg, implied, templates_dir):
    by_kind = lambda k: [l.label for l in layers if l.kind == k and l.ref not in implied]
    targets = []
    for l in layers:
        if l.kind == "target":
            v = choices.versions.get(l.ref, "").strip()
            targets.append(l.label + (f" {v}" if v else ""))
    roles = cfg["roles"]
    entries = []
    for role in ROLES:
        spec = roles[role]
        if spec:
            mark = " (created by tooling later)" if spec["origin"] == "tool_created" else ""
            entries.append(f"- `{spec['path']}/`: {spec.get('purpose', role)}{mark}")
    for d, purpose in sorted(cfg["dirs"].items()):
        if not any(d.startswith(s["path"] + "/") for s in roles.values() if s):
            entries.append(f"- `{d}/`: {purpose}")
    entries += ["- `.project.json`: machine-readable project descriptor (no secrets)"]
    ai_tools = [l.label for l in layers if l.kind == "ai" and not l.hidden]
    has_agent = roles["ai"] is not None
    agent_files = ""
    if has_agent:
        agent_files = ("- `.agent/MEMORY.md`: durable context a new agent should know.\n"
                       "- `.agent/CHECKPOINT.md`: where the project is right now.\n"
                       "- `.agent/DECISIONS.md`: why decisions were made.\n"
                       "- `.agent/PLANS.md`: what comes next.\n"
                       "- `.agent/QA_CHECKLIST.md`: what must be validated.\n")
    precedence = ("Precedence if they disagree: `PROJECT_SPEC.md` > `.agent/DECISIONS.md` > `.agent/CHECKPOINT.md` > "
                  "`.agent/MEMORY.md`." if has_agent else "`PROJECT_SPEC.md` is the source of truth.")
    decisions = "`.agent/DECISIONS.md`" if has_agent else "`PROJECT_SPEC.md` (add a Decisions section)"
    must_fill = list(cfg["must_fill"])
    tool = cfg["toolchain"]
    local = {"DECISIONS_PATH": decisions}
    bullet = lambda items, empty: "\n".join(f"- {fill(i, local)}" for i in items) if items else empty
    local_all = [p + "/" for p in cfg["local_paths"]] + list(cfg["local_only"])
    stack_labels = by_kind("stack")
    dist = by_kind("distribution")[0]
    dist_on = cfg["distribution"].get("enabled")
    wf_file = Path(templates_dir) / "v2" / f"git-workflow-{choices.git_workflow}.md"
    git_section = wf_file.read_text(encoding="utf-8").strip() if choices.git else "Git is not used for this project."
    desc = choices.description.strip()
    facts = [f"- Category: {', '.join(by_kind('category'))}",
             f"- Platform(s): {', '.join(by_kind('platform'))}",
             f"- Host application: {', '.join(targets) or 'none'}",
             f"- Technology stack: {', '.join(stack_labels) or 'undecided (not yet chosen)'}",
             f"- Distribution: {dist}",
             f"- AI tools: {', '.join(ai_tools) or 'none'}",
             f"- Git workflow: {choices.git_workflow if choices.git else 'Git not used'}"]
    return {
        "NAME": choices.name, "SLUG": slugify(choices.name), "DATE": date.today().isoformat(),
        "CATEGORY": ", ".join(by_kind("category")), "PLATFORMS": ", ".join(by_kind("platform")),
        "TARGETS": ", ".join(targets) or "no host application",
        "STACK": ", ".join(stack_labels) or "undecided", "STATE": ", ".join(by_kind("state")),
        "DISTRIBUTION": dist,
        "AI_TOOLS": ", ".join(ai_tools) or "none",
        "DESCRIPTION": desc,
        "DESCRIPTION_BLOCK": (f"{desc}\n\n_(Entered during project setup; please confirm.)_" if desc else "TO CONFIRM"),
        "MEMORY_DESCRIPTION": f"- Description (entered at setup): {desc}" if desc else "- Description: not yet provided",
        "MEMORY_FACTS": "\n".join(facts),
        "PLATFORMS_BLOCK": "\n".join(f"- {x}" for x in by_kind("platform")),
        "TARGETS_BLOCK": ("\n".join(f"- {x}" for x in targets) if targets
                          else "None: this is a standalone product (confirm if that is wrong)."),
        "STACK_BLOCK": ("\n".join(f"- {x}" for x in stack_labels) if stack_labels
                        else "Undecided. TO CONFIRM; no framework-specific structure has been created."),
        "TOOLCHAIN_BLOCK": ("\n".join(f"- {k}: {v}" for k, v in tool.items())
                            + "\n(Defaults from the project profile; confirm.)") if tool
                           else "None declared yet. TO CONFIRM.",
        "DISTRIBUTION_BLOCK": (f"- {dist}" if dist_on else "No packaged release planned yet. TO CONFIRM."),
        "GIT_WORKFLOW": choices.git_workflow, "GIT_SECTION": git_section,
        "STARTUP_AGENT": ", `.agent/MEMORY.md`, `.agent/CHECKPOINT.md`, `.agent/PLANS.md`" if has_agent else "",
        "AGENT_FILES": agent_files, "FOLDER_MAP": "\n".join(entries),
        "COMMANDS": "\n".join(cfg["commands"]) or "# (none yet; add them here)",
        "CONVENTIONS": bullet(cfg["conventions"], "- (none yet)"),
        "DONTS": bullet(cfg["donts"], "- (none)"),
        "QA_ITEMS": "\n".join(f"- [ ] {fill(q, local)}" for q in cfg["qa"]),
        "PRECEDENCE": precedence,
        "CHECK_STEP": (", then `python .agent/check.py`, and `python .agent/safety_check.py` before any commit"
                       if has_agent else ""),
        "QA_PATH": ".agent/QA_CHECKLIST.md" if has_agent else "the checklist in PROJECT_SPEC.md",
        "QUESTIONS": "\n".join(f"- {fill(q, local)}" for q in cfg["questions"]),
        "LOCAL_ONLY": ", ".join(f"`{x}`" for x in local_all) or "none declared",
        "WATCH": ", ".join(f"`{x}`" for x in cfg["watch"]) or "none",
        "PROTECTED": ", ".join(f"`{x}`" for x in cfg["protected_paths"]) or "none declared",
        "LARGE_MB": str(cfg["large_file_warn_mb"]),
        "TOOLCHAIN": "\n".join(f"- {k}: {v}" for k, v in tool.items()) or "- none declared",
        "MUSTFILL": repr(must_fill), "MUSTFILL_MD": ", ".join(f"`{m}`" for m in must_fill),
    }


def _descriptor(choices, layers, implied, cfg, hashes, feature_ids):
    roles = {}
    for role, spec in cfg["roles"].items():
        if spec:
            roles[role] = {"path": spec["path"], "origin": spec["origin"]}
    pick = lambda k: [l for l in layers if l.kind == k and not l.hidden]
    targets = []
    for l in pick("target"):
        t = {"id": l.id}
        v = choices.versions.get(l.ref, "").strip()
        if v:
            t["version"] = v
        targets.append(t)
    dist = cfg["distribution"]
    dist_out = {"enabled": bool(dist.get("enabled", False))}
    if dist_out["enabled"]:
        dist_out["type"] = dist.get("type")
        dist_out["provenance"] = dist.get("provenance", {"record": []})
    return {
        "schema_version": 1,
        "name": choices.name,
        "slug": slugify(choices.name),
        "description": choices.description.strip(),
        "category": pick("category")[0].id,
        "platforms": [{"id": l.id} for l in pick("platform")],
        "targets": targets,
        "stack": [l.id for l in pick("stack")],
        "stack_status": "chosen" if pick("stack") else "undecided",
        "state": pick("state")[0].id,
        "layout": {"roles": roles, "protected_paths": list(cfg["protected_paths"])},
        "toolchain": dict(cfg["toolchain"]),
        "git": {"enabled": choices.git, "default_branch": "main", "workflow": choices.git_workflow,
                "branch_creation": "manual", "worktrees": "optional", "commit_policy": "ask"},
        "security": {"secrets": "never_commit",
                     "local_only": [p + "/" for p in cfg["local_paths"]] + list(cfg["local_only"]),
                     "secret_patterns": [x for x in cfg["secret"] if not x.startswith("!")],
                     "generated": [f"{s['path']}/" for s in cfg["roles"].values() if s and s["origin"] == "tool_created"]
                                  + list(cfg["generated"]),
                     "large_file_warn_mb": cfg["large_file_warn_mb"], "watch_patterns": list(cfg["watch"])},
        "features": {fid: any(l.ref == f"feature:{fid}" for l in layers) for fid in feature_ids},
        "references": [],
        "development": {"ai": [l.id for l in pick("ai")]},
        "distribution": dist_out,
        "profiles": {"format": SUPPORTED_FORMAT,
                     "layers": [dict({"kind": l.kind, "id": l.id, "version": l.version},
                                     **({"implied": True} if l.ref in implied else {})) for l in layers]},
        "answer_source": dict(choices.sources),
        "scaffold": {"tool_version": TOOL_VERSION, "created": date.today().isoformat(),
                     "managed_files": hashes, "managed_blocks": []},
    }


def resolve(choices, catalog, parent, templates_dir=TEMPLATES_DIR):
    """Compose, validate and render the whole project in memory. Raises ResolveError."""
    problems = []
    if choices.git_workflow not in git_workflows(templates_dir):
        problems.append(f"Unknown Git workflow '{choices.git_workflow}'. Available: "
                        f"{', '.join(git_workflows(templates_dir))}")
    if not choices.name.strip():
        problems.append("A project name is required.")
    if not slugify(choices.name):
        problems.append("The project name needs at least one letter or number.")
    problems += [f"Folder name: {m}" for m in pathsafe.check_component(choices.folder)]
    layers, implied, p = expand(choices, catalog)
    problems += p
    if problems:
        raise ResolveError(problems)
    problems += validate_selection(layers, choices)
    if problems:
        raise ResolveError(problems)

    cfg = merge(layers, choices)
    proposed = Path(parent).expanduser().absolute() / choices.folder
    link = pathsafe.linked_ancestor(proposed)
    if link is not None:
        raise ResolveError([f"{link} is a link or reparse point; choose a real folder"])
    root = Path(parent).expanduser().resolve() / choices.folder
    errs, warns = pathsafe.check_target_root(root)
    problems += errs
    problems += _check_paths(cfg, templates_dir)

    # plan: explicit directories and files
    files_tpl = dict(cfg["files"])
    for path in cfg["json_merge"]:
        files_tpl.setdefault(path, None)
    explicit_dirs = {s["path"] for s in cfg["roles"].values() if s and s["origin"] != "tool_created"}
    explicit_dirs |= set(cfg["dirs"])
    for d in sorted(explicit_dirs):
        in_local = any(d == lp or d.startswith(lp + "/") for lp in cfg["local_paths"])
        if not in_local and not any(f.startswith(d.rstrip("/") + "/") for f in files_tpl):
            files_tpl.setdefault(f"{d.rstrip('/')}/.gitkeep", None)
    all_paths = list(files_tpl) + sorted(explicit_dirs) + [".gitignore", ".project.json"]
    problems += pathsafe.casefold_collisions(all_paths)
    for f in files_tpl:
        if f in explicit_dirs or f in (".gitignore", ".project.json"):
            problems.append(f"'{f}' is both a file and a folder or a reserved name.")
    for f in all_paths:
        if len(str(root)) + 1 + len(f) > pathsafe.MAX_FULL:
            problems.append(f"'{f}' would make the full path too long.")
    if problems:
        raise ResolveError(dict.fromkeys(problems))

    tokens = _tokens(choices, layers, cfg, implied, templates_dir)
    contents, template_of, hashes = {}, {}, []
    for path, tpl in files_tpl.items():
        text = "" if tpl is None else fill((Path(templates_dir) / tpl).read_text(encoding="utf-8"), tokens)
        contents[path] = text
        template_of[path] = tpl or "(generated)"
    # Contribution-only files start as objects, rather than empty placeholder files.
    for path in cfg["json_merge"]:
        if path not in cfg["files"]:
            contents.pop(path, None)
    _merge_json(contents, template_of, cfg["json_merge"], tokens)
    contents[".gitignore"] = _gitignore(cfg)
    template_of[".gitignore"] = "(generated)"
    for path in sorted(contents):
        hashes.append({"path": path, "template": template_of[path],
                       "sha256": hashlib.sha256(contents[path].encode("utf-8")).hexdigest()})
    feature_ids = sorted(l.id for l in catalog.values() if l.kind == "feature")
    descriptor = _descriptor(choices, layers, implied, cfg, hashes, feature_ids)
    contents[".project.json"] = json.dumps(descriptor, indent=2, ensure_ascii=False) + "\n"
    template_of[".project.json"] = "(generated)"

    warnings = list(warns) + list(cfg["warnings"]) + [f"Note: {r}" for r in cfg["recommendations"]]
    warnings += gitops.parent_warnings(root) if choices.git else []
    return Resolved(choices, layers, implied, cfg, root, contents, template_of, sorted(explicit_dirs),
                    warnings, descriptor)
